import gradio as gr
import os

# README Generator Function
def generate_readme(name, description, technologies, features, installation):

    if not name or not description:
        return "Please enter Project Name and Description.", None

    readme = f"""# {name}

## Project Description
{description}

## Technologies Used
{technologies}

## Features
{features}

## Installation Instructions
{installation}

## Generated By
Smart GitHub README Generator
"""

    file_path = "/content/README.md"

    with open(file_path, "w") as file:
        file.write(readme)

    return readme, file_path


# Create Web Application
with gr.Blocks(title="Smart GitHub README Generator") as app:

    gr.Markdown("# 📘 Smart GitHub README Generator")

    gr.Markdown(
        "Generate professional README files for your GitHub projects."
    )

    name = gr.Textbox(label="Project Name")

    description = gr.Textbox(
        label="Project Description",
        lines=3
    )

    technologies = gr.Textbox(
        label="Technologies Used"
    )

    features = gr.Textbox(
        label="Project Features",
        lines=4
    )

    installation = gr.Textbox(
        label="Installation Instructions",
        lines=3
    )

    generate = gr.Button("Generate README 🚀")

    preview = gr.Markdown()

    download = gr.File(label="Download README")

    generate.click(
        fn=generate_readme,
        inputs=[
            name,
            description,
            technologies,
            features,
            installation
        ],
        outputs=[preview, download]
    )

# Launch Application
app.launch(share=True)